  /// إرجاع الاسم المعروض حسب اللغة. [locale] = ar / en / tr
  static String display(String locale, String nameAr) {
    if (nameAr.isEmpty) return nameAr;
    if (locale == 'ar') return nameAr;
    if (locale == 'en') return _en[nameAr] ?? _trProvincesEn[nameAr] ?? nameAr;
    if (locale == 'tr') return _tr[nameAr] ?? _trProvincesTr[nameAr] ?? nameAr;
    return _en[nameAr] ?? _trProvincesEn[nameAr] ?? nameAr;
  }

  /// رمز دولة (ISO) أو نص منطقة مع الترجمة عند الإمكان.
  static String segmentForUi(String locale, String raw) {
    final v = raw.trim();
    if (v.isEmpty) return '';
    final u = v.toUpperCase();
    if (u == 'SY') return display(locale, 'سوريا');
    if (u == 'TR') return display(locale, 'تركيا');
    return display(locale, v);
  }

  /// دولة - محافظة - مقاطعة (الأجزاء غير الفارغة فقط).
  static String formatCountryProvinceDistrict(
    String locale, {
    String? country,
    String? city,
    String? district,
  }) {
    final parts = <String>[];
    void add(String? s) {
      if (s == null) return;
      final seg = segmentForUi(locale, s);
      if (seg.isNotEmpty) parts.add(seg);
    }

    add(country);
    add(city);
    add(district);
    return parts.join(' - ');
  }
